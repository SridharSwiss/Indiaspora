// Builds src/lib/seoSummaries.ts: an open SEO summary for every members-only page.
// Run after adding or editing gated pages:  node scripts/gen-seo-summaries.mjs
import { readFileSync, writeFileSync, readdirSync, statSync } from "fs";
import { join, relative } from "path";

const ROOT = "src/app/(pages)";
const GATED = ["community", "living", "food", "business", "culture", "events", "cities", "resources"];
const out = {};

function walk(dir) {
  for (const f of readdirSync(dir)) {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) walk(p);
    else if (f === "page.tsx") handle(p);
  }
}
const clean = s => s.replace(/&apos;/g, "'").replace(/&amp;/g, "&").replace(/&ldquo;|&rdquo;/g, '"').replace(/&mdash;/g, "—").replace(/\s+/g, " ").trim();
const str = (src, re) => { const m = src.match(re); return m ? clean(m[2]) : undefined; };
const Q = `(["'\`])((?:(?!\\1)[^\\n])+)\\1`; // quoted string, same quote both ends

function handle(file) {
  const route = "/" + relative(ROOT, file).replace(/\\/g, "/").replace(/\/page\.tsx$/, "");
  const parts = route.split("/").filter(Boolean);
  if (parts.length < 2 || !GATED.includes(parts[0]) || route.includes("[")) return;
  const src = readFileSync(file, "utf8");
  const meta = src.slice(src.indexOf("metadata"), src.indexOf("metadata") + 3000);
  const R = (pre) => new RegExp(pre + Q);
  const title = str(meta, R("title:\\s*")) ?? str(src, R("PageHeader[\\s\\S]*?\\btitle="));
  const description = str(meta, R("description:\\s*")) ?? str(src, R("\\bsubtitle="));
  const heading = str(src, R("PageHeader[\\s\\S]*?\\btitle=")) ?? title;
  const subtitle = str(src, R("PageHeader[\\s\\S]*?\\bsubtitle="));
  const heroImage = str(src, R("heroImage="));
  const sections = [...new Set([
    ...[...src.matchAll(/<h2[^>]*>\s*([^<{]{4,90}?)\s*<\/h2>/g)].map(m => clean(m[1])),
    ...[...src.matchAll(/<Section[^>]*\btitle=["']([^"']{4,90})["']/g)].map(m => clean(m[1])),
  ])].slice(0, 8);
  if (!title && !heading) return;
  out[route] = { title: title ?? heading, heading: heading ?? title, description: description ?? subtitle ?? "", subtitle, heroImage, sections };
}

walk(ROOT);
const body = `// AUTO-GENERATED by scripts/gen-seo-summaries.mjs — do not edit by hand.\n` +
  `export type SeoSummary = { title: string; heading: string; description: string; subtitle?: string; heroImage?: string; sections: string[] };\n` +
  `export const SEO_SUMMARIES: Record<string, SeoSummary> = ${JSON.stringify(out, null, 2)};\n`;
writeFileSync("src/lib/seoSummaries.ts", body);
console.log(`Wrote ${Object.keys(out).length} summaries`);
